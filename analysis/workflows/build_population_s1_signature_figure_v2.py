"""Build the current 40-tile one-row, three-panel S1 signature figure.

The figure is deliberately restricted to three complementary population-level
views: (a) absolute backscatter context, (b) one paired change per reference
event, and (c) the event-aligned temporal response.  The validated cohort and
reference ledger are read from the frozen v1 signature products; no detector
is run and no Table 2 is generated by this workflow.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any

import matplotlib
import numpy as np
import pandas as pd

matplotlib.use("Agg")
import matplotlib.pyplot as plt


BANDS = ("VV", "VH")
BAND_COLOURS = {"VV": "#2369a1", "VH": "#d55e00"}
RELATIVE_MONTHS = tuple(range(-12, 13))
FIGURE_WIDTH_IN = 180.0 / 25.4
FIGURE_HEIGHT_IN = 62.0 / 25.4
DEFAULT_SEED = 20260822
EXPECTED = {
    "national_polygons": 3498,
    "strict_events": 1018,
    "strict_reference_polygons": 462,
    "strict_spatial_blocks": 57,
}


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def strict_event_ids(events: pd.DataFrame) -> pd.Index:
    required = {
        "event_id", "sample_id", "spatial_block_id", "tile_id",
        "event_month", "band", "pre_db", "post_db", "post_delta_db",
    }
    missing = required.difference(events.columns)
    if missing:
        raise ValueError(f"Event table is missing columns: {sorted(missing)}")
    local = events.loc[events.band.isin(BANDS)].copy()
    counts = local.groupby(["event_id", "band"], sort=False).size().unstack(fill_value=0)
    for band in BANDS:
        if band not in counts:
            counts[band] = 0
    valid = counts.index[(counts.loc[:, list(BANDS)] == 1).all(axis=1)]
    metadata = local.loc[local.event_id.isin(valid)].groupby("event_id")[
        ["sample_id", "spatial_block_id", "tile_id", "event_month"]
    ].nunique(dropna=False)
    if not metadata.eq(1).all().all():
        raise ValueError("VV/VH metadata are inconsistent within an event")
    return pd.Index(sorted(valid.astype(str)), name="event_id")


def event_metadata(events: pd.DataFrame, event_ids: pd.Index) -> pd.DataFrame:
    local = events.loc[events.event_id.astype(str).isin(set(event_ids))].copy()
    meta = local[
        ["event_id", "sample_id", "spatial_block_id", "tile_id", "event_month"]
    ].drop_duplicates("event_id")
    meta["event_id"] = meta.event_id.astype(str)
    meta["event_month"] = pd.to_datetime(meta.event_month)
    return meta.sort_values("event_id").reset_index(drop=True)


def filter_aligned(aligned: pd.DataFrame, event_ids: pd.Index) -> pd.DataFrame:
    required = {
        "event_id", "sample_id", "spatial_block_id", "tile_id", "band",
        "relative_month", "delta_db",
    }
    missing = required.difference(aligned.columns)
    if missing:
        raise ValueError(f"Aligned table is missing columns: {sorted(missing)}")
    local = aligned.loc[
        aligned.event_id.astype(str).isin(set(event_ids))
        & aligned.band.isin(BANDS)
        & aligned.relative_month.isin(RELATIVE_MONTHS)
    ].copy()
    duplicate = local.duplicated(["event_id", "band", "relative_month"])
    if duplicate.any():
        raise ValueError("Aligned table contains duplicate event-band-month rows")
    expected_rows = len(event_ids) * len(BANDS) * len(RELATIVE_MONTHS)
    if len(local) != expected_rows:
        raise ValueError(f"Expected {expected_rows} aligned rows, found {len(local)}")
    return local


def monthly_summary(aligned: pd.DataFrame) -> pd.DataFrame:
    return (
        aligned.groupby(["band", "relative_month"], sort=True)
        .delta_db.agg(
            n="count",
            q25=lambda x: x.quantile(0.25),
            median="median",
            q75=lambda x: x.quantile(0.75),
        )
        .reset_index()
    )


def block_curve_bootstrap(
    aligned: pd.DataFrame,
    metadata: pd.DataFrame,
    replicates: int,
    seed: int,
) -> pd.DataFrame:
    """Return 95% spatial-block intervals for the aligned median curve."""

    if replicates <= 0:
        raise ValueError("replicates must be positive")
    event_order = metadata.event_id.astype(str).tolist()
    block_by_event = metadata.set_index("event_id").spatial_block_id.astype(str)
    blocks = np.asarray(sorted(block_by_event.unique()), dtype=object)
    rng = np.random.default_rng(seed)
    records: list[dict[str, Any]] = []
    for band in BANDS:
        matrix = (
            aligned.loc[aligned.band.eq(band)]
            .assign(event_id=lambda d: d.event_id.astype(str))
            .pivot(index="event_id", columns="relative_month", values="delta_db")
            .reindex(index=event_order, columns=RELATIVE_MONTHS)
        )
        values = matrix.to_numpy(dtype=float)
        block_index = {
            block: np.flatnonzero(block_by_event.reindex(matrix.index).to_numpy() == block)
            for block in blocks
        }
        curves = np.empty((replicates, len(RELATIVE_MONTHS)), dtype=float)
        for i in range(replicates):
            sampled = rng.choice(blocks, size=len(blocks), replace=True)
            rows = np.concatenate([block_index[block] for block in sampled])
            curves[i] = np.nanmedian(values[rows], axis=0)
        low, high = np.nanquantile(curves, [0.025, 0.975], axis=0)
        for month, lo, hi in zip(RELATIVE_MONTHS, low, high):
            records.append({
                "band": band,
                "relative_month": int(month),
                "bootstrap_lower": float(lo),
                "bootstrap_upper": float(hi),
                "replicates": int(replicates),
                "seed": int(seed),
            })
    return pd.DataFrame(records)


def draw_violin(ax: plt.Axes, values: np.ndarray, position: float, colour: str,
                alpha: float, width: float = 0.62) -> None:
    finite = np.asarray(values, dtype=float)
    finite = finite[np.isfinite(finite)]
    violin = ax.violinplot(
        [finite], positions=[position], orientation="horizontal", widths=width,
        showmeans=False, showmedians=False, showextrema=False,
    )
    body = violin["bodies"][0]
    body.set_facecolor(colour)
    body.set_edgecolor("#4d4d4d")
    body.set_linewidth(0.35)
    body.set_alpha(alpha)
    q25, med, q75 = np.quantile(finite, [0.25, 0.5, 0.75])
    ax.plot([q25, q75], [position, position], color="black", linewidth=1.0, zorder=4)
    ax.scatter([med], [position], s=9, color="white", edgecolor="black",
               linewidth=0.4, zorder=5)


def render_figure(
    national_values: np.ndarray,
    events: pd.DataFrame,
    aligned: pd.DataFrame,
    table_summary: pd.DataFrame,
    curve: pd.DataFrame,
    seed: int,
) -> tuple[plt.Figure, dict[str, Any]]:
    plt.rcParams.update({
        "font.family": "sans-serif",
        "font.sans-serif": ["Arial", "DejaVu Sans"],
        "font.size": 7.0,
        "axes.titlesize": 7.6,
        "axes.labelsize": 6.8,
        "xtick.labelsize": 6.2,
        "ytick.labelsize": 6.2,
        "legend.fontsize": 6.0,
        "axes.linewidth": 0.55,
        "pdf.fonttype": 42,
        "ps.fonttype": 42,
        "svg.fonttype": "none",
    })
    fig, axes = plt.subplots(1, 3, figsize=(FIGURE_WIDTH_IN, FIGURE_HEIGHT_IN))
    fig.subplots_adjust(left=0.055, right=0.995, bottom=0.23, top=0.83, wspace=0.40)
    national = {
        band: national_values[:, i, :][np.isfinite(national_values[:, i, :])]
        for i, band in enumerate(BANDS)
    }

    # Panel A: absolute-state context.
    ax = axes[0]
    positions = [5, 4, 3, 1, 0, -1]
    labels = ["VV national", "VV pre", "VV event/+2",
              "VH national", "VH pre", "VH event/+2"]
    distributions = [
        national["VV"],
        events.loc[events.band.eq("VV"), "pre_db"].to_numpy(),
        events.loc[events.band.eq("VV"), "post_db"].to_numpy(),
        national["VH"],
        events.loc[events.band.eq("VH"), "pre_db"].to_numpy(),
        events.loc[events.band.eq("VH"), "post_db"].to_numpy(),
    ]
    colours = ["#9e9e9e", BAND_COLOURS["VV"], BAND_COLOURS["VV"],
               "#9e9e9e", BAND_COLOURS["VH"], BAND_COLOURS["VH"]]
    alphas = [0.38, 0.25, 0.72, 0.38, 0.25, 0.72]
    for vals, pos, col, alpha in zip(distributions, positions, colours, alphas):
        draw_violin(ax, vals, pos, col, alpha)
    ax.set_yticks(positions, labels)
    ax.set_xlim(-20, -3)
    ax.set_xticks([-20, -16, -12, -8, -4])
    ax.set_xlabel("Backscatter (dB)")
    ax.set_title("(a) Absolute-state context", loc="left", fontweight="bold")
    ax.axhline(2, color="#cfcfcf", linewidth=0.35)
    ax.grid(axis="x", color="#dddddd", linewidth=0.4, alpha=0.8)
    ax.spines[["top", "right"]].set_visible(False)

    # Panel B: one paired response per event.
    ax = axes[1]
    rng = np.random.default_rng(seed)
    for pos, band in enumerate(BANDS, start=1):
        vals = events.loc[events.band.eq(band), "post_delta_db"].to_numpy(dtype=float)
        violin = ax.violinplot([vals], positions=[pos], widths=0.66,
                               showmeans=False, showmedians=False, showextrema=False)
        body = violin["bodies"][0]
        body.set_facecolor(BAND_COLOURS[band])
        body.set_edgecolor(BAND_COLOURS[band])
        body.set_alpha(0.18)
        ax.scatter(pos + rng.uniform(-0.16, 0.16, len(vals)), vals, s=1.8,
                   color=BAND_COLOURS[band], alpha=0.16, linewidth=0, rasterized=True)
        summary = table_summary.loc[table_summary.band.eq(band)].iloc[0]
        median = float(summary.paired_delta_median_db)
        low = float(summary.paired_delta_block_bootstrap_lower_db)
        high = float(summary.paired_delta_block_bootstrap_upper_db)
        ax.errorbar([pos], [median], yerr=[[median - low], [high - median]],
                    fmt="D", color="black", markerfacecolor="white", markersize=3.0,
                    linewidth=0.9, capsize=2.0, zorder=5)
        pct = float(summary.proportion_negative) * 100.0
        ax.text(pos, 2.15, f"{pct:.1f}% < 0", ha="center", va="top", fontsize=5.5,
                color="#333333", fontweight="bold")
    ax.axhline(0, color="black", linestyle="--", linewidth=0.7)
    ax.set_xlim(0.45, 2.55)
    ax.set_ylim(-7.2, 2.55)
    ax.set_xticks([1, 2], BANDS)
    ax.set_yticks([-6, -3, 0, 2])
    ax.set_ylabel("Event/+2 minus pre-event (dB)")
    ax.set_title("(b) Paired event response", loc="left", fontweight="bold")
    ax.text(0.02, 0.03, "one point = one dated polygon event\nwhite diamond = median; bar = 95% block interval",
            transform=ax.transAxes, ha="left", va="bottom", fontsize=5.1, color="#4d4d4d")
    ax.grid(axis="y", color="#dddddd", linewidth=0.4, alpha=0.8)
    ax.spines[["top", "right"]].set_visible(False)

    # Panel C: event-aligned trajectory.
    ax = axes[2]
    for band in BANDS:
        local = curve.loc[curve.band.eq(band)].sort_values("relative_month")
        boot = curve.loc[curve.band.eq(band)].sort_values("relative_month")
        x = local.relative_month.to_numpy(dtype=float)
        colour = BAND_COLOURS[band]
        ax.fill_between(x, local["q25"], local["q75"], color=colour, alpha=0.14, linewidth=0)
        ax.fill_between(x, boot["bootstrap_lower"], boot["bootstrap_upper"],
                        color=colour, alpha=0.23, linewidth=0)
        ax.plot(x, local["median"], color=colour, linewidth=1.45, label=band)
    ax.axvline(0, color="black", linestyle="--", linewidth=0.7)
    ax.axhline(0, color="#666666", linestyle=":", linewidth=0.6)
    ax.set_xlim(-12, 12)
    ax.set_ylim(-3.5, 0.65)
    ax.set_xticks([-12, -6, 0, 6, 12])
    ax.set_yticks([-3, -2, -1, 0])
    ax.set_xlabel("Months relative to reference event")
    ax.set_ylabel("Change from pre-event median (dB)")
    ax.set_title("(c) Event-aligned trajectory", loc="left", fontweight="bold")
    ax.legend(loc="lower right", frameon=False, ncol=2, handlelength=1.2,
              columnspacing=0.7)
    ax.text(0.02, 0.03, "dark: IQR; light: block 95%",
            transform=ax.transAxes, ha="left", va="bottom", fontsize=5.1, color="#4d4d4d")
    ax.grid(color="#dddddd", linewidth=0.4, alpha=0.8)
    ax.spines[["top", "right"]].set_visible(False)

    diagnostics = {
        "figure_width_mm": 180.0,
        "figure_height_mm": 62.0,
        "panels": {
            "a": "absolute national polygon-month context and paired states",
            "b": "one paired event-level delta per support-qualified polygon event",
            "c": "event-aligned median/IQR with spatial-block 95% interval",
        },
        "seed": int(seed),
        "backend": "matplotlib",
    }
    return fig, diagnostics


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input-dir", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--bootstrap-replicates", type=int, default=5000)
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    parser.add_argument("--dpi", type=int, default=600)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    input_dir = args.input_dir.resolve()
    output_dir = args.output_dir.resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    paths = {
        "national_metadata": input_dir / "national_balsa_series_metadata.parquet",
        "national_values": input_dir / "national_balsa_series.npz",
        "event_summary": input_dir / "historical_event_summary.csv",
        "event_aligned": input_dir / "historical_event_aligned.parquet",
        "table_summary": input_dir / "table_s1_signature_summary.csv",
        "source_manifest": input_dir / "signature_analysis_manifest.json",
    }
    missing = [str(path) for path in paths.values() if not path.exists()]
    if missing:
        raise FileNotFoundError(f"Missing frozen inputs: {missing}")
    metadata_all = pd.read_parquet(paths["national_metadata"])
    with np.load(paths["national_values"]) as arrays:
        national_values = arrays["values"].copy()
    events_all = pd.read_csv(paths["event_summary"], parse_dates=["event_month"])
    aligned_all = pd.read_parquet(paths["event_aligned"])
    table_summary = pd.read_csv(paths["table_summary"])
    event_ids = strict_event_ids(events_all)
    events = events_all.loc[events_all.event_id.astype(str).isin(set(event_ids))].copy()
    aligned = filter_aligned(aligned_all, event_ids)
    event_meta = event_metadata(events, event_ids)
    counts = {
        "national_polygons": int(metadata_all.sample_id.nunique()),
        "strict_events": int(len(event_ids)),
        "strict_reference_polygons": int(event_meta.sample_id.nunique()),
        "strict_spatial_blocks": int(event_meta.spatial_block_id.nunique()),
        "strict_tiles": int(event_meta.tile_id.nunique()),
        "aligned_rows": int(len(aligned)),
    }
    for key, value in EXPECTED.items():
        if counts[key] != value:
            raise ValueError(f"Frozen count mismatch for {key}: {counts[key]} != {value}")
    if national_values.shape[0] != counts["national_polygons"]:
        raise ValueError("National metadata and value arrays have different polygon counts")
    monthly = monthly_summary(aligned)
    bootstrap = block_curve_bootstrap(aligned, event_meta, args.bootstrap_replicates, args.seed)
    curve = monthly.merge(bootstrap, on=["band", "relative_month"], validate="one_to_one")
    curve.to_csv(output_dir / "event_aligned_monthly_summary.csv", index=False)
    events.sort_values(["event_id", "band"]).to_csv(output_dir / "paired_event_changes.csv", index=False)
    counts["national_valid_polygon_months_both_bands"] = int(
        np.isfinite(national_values).all(axis=1).sum()
    )
    fig, layout = render_figure(
        national_values, events, aligned, table_summary, curve, args.seed
    )
    stem = output_dir / "figure_03_population_s1_signatures_v2"
    fig.savefig(stem.with_suffix(".pdf"), bbox_inches="tight", metadata={"Title": "Population Sentinel-1 stand-disturbance signatures"})
    fig.savefig(stem.with_suffix(".svg"), bbox_inches="tight")
    fig.savefig(stem.with_suffix(".png"), dpi=args.dpi, bbox_inches="tight")
    fig.savefig(stem.with_suffix(".tiff"), dpi=args.dpi, bbox_inches="tight")
    plt.close(fig)
    manifest = {
        "schema_version": 2,
        "workflow": "population_s1_signatures_three_panel",
        "claim": "Reference-dated historical disturbances show repeatable within-stand negative VV/VH responses.",
        "counts": counts,
        "protocol": {
            "bands": list(BANDS),
            "pre_event": "relative months -12 through -3",
            "event_post": "relative months 0 through +2",
            "aligned_curve": "relative months -12 through +12",
            "event_unit": "one dated polygon event after within-event track fusion",
            "uncertainty": "5,000 complete spatial-block bootstrap resamples",
            "seed": int(args.seed),
            "no_table_2": True,
        },
        "layout": layout,
        "inputs": {
            name: {"path": str(path), "sha256": sha256(path), "size_bytes": path.stat().st_size}
            for name, path in paths.items()
        },
    }
    (output_dir / "figure_03_population_s1_signatures_v2_manifest.json").write_text(
        json.dumps(manifest, indent=2), encoding="utf-8"
    )
    print(json.dumps(counts, indent=2))
    print(f"Figure written to {stem}.pdf/.svg/.png/.tiff")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
