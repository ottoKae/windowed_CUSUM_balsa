"""Generate the default-deny ignore rules from the maintained public file list."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def main():
    config = json.loads((ROOT / "configs/public_export.json").read_text(encoding="utf-8"))
    sources = set(config["files"]) | set(config["files"].values())
    parents = {p.as_posix() for name in sources for p in Path(name).parents if p != Path(".")}
    lines = ["# Generated by tooling/release/update_public_ignore.py from configs/public_export.json.",
             "# Everything not explicitly selected stays local. This does not remove Git history.", "*", ""]
    lines += [f"!/{name}/" for name in sorted(parents, key=lambda p: (p.count('/'), p))]
    lines += [f"!/{name}" for name in sorted(sources)]
    lines += ["!/PUBLIC_FILES.json"]
    (ROOT / ".gitignore").write_bytes(("\n".join(lines) + "\n").encode("utf-8"))


if __name__ == "__main__":
    main()
